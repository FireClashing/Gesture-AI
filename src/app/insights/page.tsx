import PageHeader from "@/components/PageHeader";
import { metrics } from "@/lib/signa/metrics";
import { ALPHABET_LABELS } from "@/lib/signa/translations";

const pct = (n: number) => `${(n * 100).toFixed(1)}%`;
const card = "rounded-2xl border border-slate-800 bg-[#101827] p-5";
const th = "px-3 py-2 text-left text-[11px] font-bold uppercase tracking-wider text-slate-400";
const td = "px-3 py-2 text-sm text-slate-200";

export const metadata = { title: "Model Insights · Signa" };

export default function InsightsPage() {
  const m = metrics;
  const e = m.evaluation;
  const maxCount = Math.max(1, ...Object.values(m.labelCounts));
  const stats = [
    { value: m.samples.used, label: "Samples used", detail: `${m.samples.raw} raw · ${m.samples.raw - m.samples.used} removed as invalid or near-duplicate` },
    { value: `${m.labels.length} / 26`, label: "Alphabet labels covered", detail: m.labels.join(" · ") },
    { value: pct(e.macroF1), label: "Held-out macro-F1", detail: `${e.strategy}, ${e.groups} groups` },
    { value: `${m.signers} / ${m.sessions}`, label: "Signers / sessions", detail: `${m.featureCount} features per sample` },
  ];

  return (
    <div className="p-4 md:p-6">
      <PageHeader title="Model Insights" description={`Generated by ml/train.py on ${new Date(m.generatedAt).toLocaleString("en-IN")}. Re-run \`npm run train\` to refresh.`} />
      <div className="mx-auto max-w-6xl space-y-5 text-slate-100">
        {m.warnings.length > 0 && (
          <section className="rounded-2xl border border-amber-500/30 bg-amber-500/5 p-5" aria-label="Data quality warnings">
            <h2 className="text-sm font-bold text-amber-200">Read before trusting these numbers</h2>
            <ul className="mt-3 list-disc space-y-2 pl-5 text-sm leading-6 text-slate-300">
              {m.warnings.map((w) => <li key={w}>{w}</li>)}
            </ul>
          </section>
        )}

        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
          {stats.map((s) => (
            <div key={s.label} className={card}>
              <p className="text-3xl font-extrabold text-white">{s.value}</p>
              <p className="mt-2 text-sm font-semibold text-slate-200">{s.label}</p>
              <p className="mt-2 text-xs text-slate-500">{s.detail}</p>
            </div>
          ))}
        </div>

        <section className={card}>
          <h2 className="text-base font-bold text-white">Model comparison</h2>
          <p className="mt-1 text-xs text-slate-400">Each candidate is trained on all groups but one and tested on the held-out group; scores pool every fold.</p>
          <div className="mt-3 overflow-x-auto">
            <table className="w-full min-w-[420px]">
              <thead><tr><th className={th}>Model</th><th className={th}>Accuracy</th><th className={th}>Macro-F1</th><th className={th}>Runs in browser</th><th className={th}></th></tr></thead>
              <tbody>
                {e.candidates.map((c) => (
                  <tr key={c.name} className="border-t border-slate-800">
                    <td className={`${td} font-mono`}>{c.name}</td><td className={td}>{pct(c.accuracy)}</td><td className={td}>{pct(c.macroF1)}</td>
                    <td className={td}>{c.exportable ? "yes" : "no"}</td>
                    <td className={td}>{c.name === e.selected && <span className="rounded-full bg-indigo-500/20 px-2 py-0.5 text-xs font-semibold text-indigo-300">deployed</span>}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>

        <section className={card}>
          <h2 className="text-base font-bold text-white">Samples per alphabet letter</h2>
          <div className="mt-4 grid grid-cols-1 gap-x-8 gap-y-2 sm:grid-cols-2">
            {ALPHABET_LABELS.map((letter) => {
              const n = m.labelCounts[letter] ?? 0;
              return (
                <div key={letter} className="flex items-center gap-3">
                  <span className="w-5 text-sm font-bold text-white">{letter}</span>
                  <div className="h-2 flex-1 overflow-hidden rounded-full bg-slate-800">
                    <div className={`h-full rounded-full ${n ? "bg-indigo-500" : "bg-red-500/60"}`} style={{ width: `${Math.max(n ? 3 : 0, (n / maxCount) * 100)}%` }} />
                  </div>
                  <span className={`w-24 text-right text-xs ${n ? "text-slate-400" : "text-red-300"}`}>{n ? `${n} samples` : "no data"}</span>
                </div>
              );
            })}
          </div>
        </section>

        <section className={card}>
          <h2 className="text-base font-bold text-white">Per-class results (held-out)</h2>
          <div className="mt-3 overflow-x-auto">
            <table className="w-full min-w-[420px]">
              <thead><tr><th className={th}>Label</th><th className={th}>Precision</th><th className={th}>Recall</th><th className={th}>F1</th><th className={th}>Support</th></tr></thead>
              <tbody>
                {e.perClass.map((c) => (
                  <tr key={c.label} className="border-t border-slate-800">
                    <td className={`${td} font-bold`}>{c.label}</td><td className={td}>{pct(c.precision)}</td><td className={td}>{pct(c.recall)}</td><td className={td}>{pct(c.f1)}</td><td className={td}>{c.support}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>

        <section className={card}>
          <h2 className="text-base font-bold text-white">Confusion matrix</h2>
          <p className="mt-1 text-xs text-slate-400">Rows are the true label, columns the prediction.</p>
          <div className="mt-3 overflow-x-auto">
            <table className="text-center">
              <thead>
                <tr><th className={th}></th>{e.confusion.labels.map((l) => <th key={l} className="px-3 py-2 text-xs font-bold text-slate-300">{l}</th>)}</tr>
              </thead>
              <tbody>
                {e.confusion.matrix.map((row, i) => (
                  <tr key={e.confusion.labels[i]}>
                    <th className="px-3 py-2 text-xs font-bold text-slate-300">{e.confusion.labels[i]}</th>
                    {row.map((v, j) => (
                      <td key={j} className={`px-3 py-2 text-sm ${i === j ? "bg-emerald-500/15 font-bold text-emerald-300" : v ? "bg-red-500/15 text-red-300" : "text-slate-600"}`}>{v}</td>
                    ))}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </section>

        <section className={card}>
          <h2 className="text-base font-bold text-white">Deployment</h2>
          <ul className="mt-2 space-y-1 text-sm text-slate-300">
            <li>API model: <code className="text-indigo-300">ml/models/{m.deployment.api}</code></li>
            <li>Browser model: {m.deployment.browser ? <code className="text-indigo-300">public/models/{m.deployment.browser}</code> : "not exportable (frontend uses the API)"}</li>
            <li>Input format: <code className="text-indigo-300">{m.inputFormat}</code> ({m.featureCount} values)</li>
          </ul>
        </section>
      </div>
    </div>
  );
}
